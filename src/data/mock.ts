/**
 * 空会话的开场白。
 *
 * ⚠️ **2026-09-24 改过三轮。** 三个靶子各管一件事，别把后一轮当成把前一轮推翻了：
 *
 * **① 不许许做不到的承诺。** 最初那句是「也可以直接问我**任何**饮食问题」——
 * 一个「任何」把边界抹掉了：用户于是拿闲聊、医疗、用药来问，而**膳享+ 那边当时
 * 没有「不归我管」这条出口**（现在补在 `dify/out-of-scope-prompt.txt` 里），
 * 它只能硬塞进一个吃的 mode，于是编出一道菜。
 *
 * **② 不许读起来像功能说明书。** ① 把招呼语一起删了，剩下的全是断言句。
 *
 * **③ 不许端着 —— 这一轮才是真正的病根。** ②③ 两版被用户退回的理由是同一个：
 * 「不够日常，很僵硬」。僵硬不在长短，在**气口**：
 *   · 分号 + 破折号（「…风险；有拿不准的，随时问我 —— 我记着…」）是**写出来的句子**，
 *     没有人那样说话。**一个标点一条短句**才对。
 *   · 「营养和风险」「饮食上的事」是**产品词**。用户嘴里说的是「这顿怎么样」。
 *   · 「健康档案」是**数据模型里的词**。真要说，就说「你的事我记着」。
 *   · 「有拿不准的」指代不清。**具体动作**（拍照片 / 直接问）比抽象名词好懂。
 *   · 「不想拍，直接问我也行」比「随时问我」暖 —— 它先替用户把「懒得拍照」这个
 *     真实顾虑说出来了，而不是等他想到。
 *
 * 口径是用户在三个候选里挑的（2026-09-24）。
 *
 * 「今天想从哪开始？」没有再回来 —— 输入框上方那三个快捷提问
 * （`QUICK_QUESTIONS`）已经在做同一件事，两句问话叠在一起是重复。
 */
