/**
 * 「分析中」那十来秒里,界面能诚实说出的六个阶段
 * ===========================================================
 * 词表的形状是**上游的真实形状**,不是我编的剧情。Dify 那张图长这样:
 *
 *     用户输入 → 代码执行 → 条件分支 ─┬─(命中拦截)→ 直接回复 2
 *                                    └─(正常)→ 知识检索 → LLM → 抽取库外菜
 *                                        → 有没有库外菜 ─┬─(有库外菜)→ Bocha Web Search
 *                                                        │   → 搜索转文本 → 营养折算
 *                                                        └─(没有)→ 合并营养
 *                                        → 合并营养 → 代码执行 2 → 直接回复
 *
 * 最显眼的一条:**「识别菜品」和「生成建议」是同一个 `LLM` 节点一次调用出来的**。
 * 想把它切成「正在识别菜品」和「正在生成建议」两句,只能按时间瞎切 ——
 * 那种进度条上游一变就跟着骗人(这一页原来那个三步动画就是这么坏的,
 * 见 `AnalyzingScreen` 那一节)。所以这里按节点切,一个节点一句话。
 *
 * ## 为什么必须单调
 *
 * `advance()` 只在新阶段**排在当前阶段之后**时才前进。两个理由:
 *
 *   1. `node_started` 不保证按拓扑序到达 —— 分支、重试、事件在传输层错序
 *      都会让它乱着来。只前进就不会来回跳:用户看到的每一句都是
 *      「已经到这一步了」,而不是「怎么又退回上一步了」。
 *   2. 顺带把那些**来不及看**的节点处理掉了:`代码执行`、`条件分支`、
 *      `抽取库外菜`、`有没有库外菜` 全都只跑 0.03 秒,映射它们等于让屏幕上
 *      闪一下莫名其妙的话。它们显式列在 `UNMAPPED_NODES` 里,不是漏了。
 *
 * ⚠️ 认不出的 title **什么都不做** —— 既不前进也不回退。往图里加节点是上游的
 * 事,客户端猜错比不动更糟(猜错的表现是屏幕上出现一句和工作流无关的话)。
 * `scripts/verify-loop.mjs` 第 9 节有一条断言盯着「yml 里的每个节点名要么在
 * 映射表里、要么在『有意不映射』名单里」,加节点忘了同步会直接红。
 */

/**
 * 阶段。**顺序就是数组 `ORDER` 里的顺序**,别去动那个数组的排列。
 *
 * 注意没有「完成」这一档:任务是不是落地了由 `PlateJob.stage` 回答,
 * 不属于「进行到哪一步」。两者混进同一个词表,就会出现「进度值说谎」
 * 那种最难查的 bug。
 */
export type AnalyzeStage =
  /** 解码 + 压缩。`startPlateJob` 同步就写进去,所以它是分析页的**首帧** */
  | 'compress'
  /** 图片正在传给 Dify。响应头回来之前这段全算它,实测稳定 ~1.5 秒 */
  | 'upload'
  /** `知识检索` —— 查膳食指南。实测 1~3 秒 */
  | 'guide'
  /** `LLM` —— 认菜 + 生成建议。**4~12 秒,这段是整场等待的大头** */
  | 'recognize'
  /** 联网查营养。只有库外菜才走这条路,实测 0~3 秒 */
  | 'search'
  /** 合并营养 → 出最终回答。~0.2 秒 */
  | 'assemble'

/**
 * 阶段顺序 —— **这个数组就是顺序本身**。
 *
 * ⚠️ 别在别处再写一份 `RANK` 常量或者 `switch` 里的序号。两份顺序一定会漂移,
 * 而漂移的表现是「进度条往前跳了一下又跳回去」这种只在某条分支上出现、
 * 极难复现的毛病。
 */
const ORDER: readonly AnalyzeStage[] = ['compress', 'upload', 'guide', 'recognize', 'search', 'assemble']

/**
 * 屏幕上那一行字。
 *
 * 全部写成「正在…」的进行时:它们描述的是**此刻正在发生的事**,而不是
 * 「已经做完了什么」。做完了的进度由秒表回答(见 `AnalyzingScreen`),
 * 这里不掺和。
 */
export const ANALYZE_STAGE_LABELS: Record<AnalyzeStage, string> = {
  compress: '正在压缩图片',
  upload: '正在上传图片',
  guide: '正在查膳食指南',
  recognize: '正在识别菜品',
  search: '正在联网查营养',
  assemble: '正在整理结果',
}

/**
 * Dify 节点名 → 阶段。键是 `dify/食衡MealBalance.yml` 里节点 `data.title` 的
 * **原文**,一个字都不能差(带空格的 `代码执行 2` 就是带空格的)。
 */
export const STAGE_OF_NODE: Record<string, AnalyzeStage> = {
  知识检索: 'guide',
  // 认菜和建议都出自这一个节点 —— 所以「识别菜品」这句要一直挂到它结束
  LLM: 'recognize',
  // 联网查营养那一段是三个节点串起来的:搜 → 转文本 → 折算成营养值
  'Bocha Web Search': 'search',
  搜索转文本: 'search',
  营养折算: 'search',
  // 收尾。两个 `直接回复` 都是终止节点,一个是正常回答、一个是过敏拦截,
  // 从用户的角度都是「在出结果」,所以映射到同一档
  合并营养: 'assemble',
  '代码执行 2': 'assemble',
  直接回复: 'assemble',
  '直接回复 2': 'assemble',
}

/**
 * **有意不映射**的节点。
 *
 * 这个名单存在的唯一理由是给 `verify-loop.mjs` 那条断言当另一半判据:
 * 上游加了新节点而这里没跟上时,断言要能红。所以往图里加节点必须同时
 * 更新这两处中的一个 —— 只把节点从 yml 里删掉、却留着这里的名字,
 * 断言同样会红(那是好事:死名字和漏名字一样会让人误判)。
 */
export const UNMAPPED_NODES: readonly string[] = [
  '用户输入', // start,没有耗时
  '代码执行', // 解析 query 里的 JSON,0.03 秒
  '条件分支', // 过敏拦截的判断,0.03 秒
  '抽取库外菜', // LLM 之后的整理,0.03 秒
  '有没有库外菜', // 决定要不要联网,0.03 秒
  /*
    「只要菜名」那条短路(App 的 `recognizeNames`)。

    它跑在**另一条请求**里,而那条请求不订阅进度 —— 它买的是「早」,不是
    「看得见」,所以这三个名字永远不会进「分析中」那一屏。认不出来不登记,
    `verify-loop` 那条「yml 里每个节点都在词表里」的断言就会红。
  */
  '只要菜名',
  '认菜',
  '直接回复 3',
]

/** 节点名 → 阶段。认不出返回 `null`(调用方据此**什么都不做**) */
export function stageOfNode(title: string): AnalyzeStage | null {
  // `?? null` 不是多余的:tsconfig 没开 noUncheckedIndexedAccess,
  // 类型上索引签名永远有值,而运行时当然没有这个键
  return STAGE_OF_NODE[title] ?? null
}

/**
 * 单调前进。`cur` 为空(还没收到过任何节点事件)时直接采纳 `next`。
 *
 * 相等时返回原值 —— 同一个节点重复上报(重试、事件重放)不该被当成新进展。
 */
export function advance(cur: AnalyzeStage | undefined, next: AnalyzeStage): AnalyzeStage {
  if (cur === undefined) return next
  return ORDER.indexOf(next) > ORDER.indexOf(cur) ? next : cur
}
