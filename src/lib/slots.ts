/**
 * 餐次的划分 —— **全 App 唯一一处定义**。
 *
 * 规则:**三餐各占一个窄窗口,窗口之外全是加餐。**
 *
 *     06:00 – 09:00   早餐
 *     09:00 – 11:00   上午加餐
 *     11:00 – 14:00   午餐
 *     14:00 – 17:00   下午加餐
 *     17:00 – 21:00   晚餐
 *     21:00 – 06:00   夜宵
 *
 * ------------------------------------------------------------
 * 为什么不是「把一天切成四段」
 * ------------------------------------------------------------
 * 原来是 `h < 10 → 早餐 / h < 15 → 午餐 / h < 21 → 晚餐 / 其余 → 加餐`,
 * 也就是把 24 小时**平铺切成不相交的四段**(见 git 历史里的 `currentSlot`)。
 * 两个后果:
 *
 *   · 「加餐」只在 21:00 之后出现 —— 这个 App 里的「加餐」实际上是**夜宵**,
 *     而上午十点、下午三点吃的那两顿无处可落,被算进了午餐/晚餐。
 *   · 三餐的窗口长得离谱:午餐 5 小时、晚餐 6 小时。
 *
 * 用户的原话:「早午餐之间可能会有加餐、午晚餐之间也可能会有加餐,而且,
 * 你的早、午、晚餐的时间段也和常理不合,时间怎么可能那么长」。
 *
 * 所以改成**窄窗口 + 空档即加餐**,并把「加餐」拆成三档
 * (上午加餐 / 下午加餐 / 夜宵)—— 它本来就对应三个不同的时段。
 *
 * ⚠️ 这次删掉了一个取值(`加餐`),所以 `SCHEMA_VERSION` 7 → 8,
 * 附带一条**不丢数据**的迁移。判据与代价见 `store/persist.ts` 的 v8 那条。
 *
 * ------------------------------------------------------------
 * 这份定义原来有两份
 * ------------------------------------------------------------
 * `recognize.ts` 的 `currentSlot()` 和 `MealSheet.tsx` 的 `inferSlot()`,
 * 两边注释互相写着「与另一边保持一致」,但**没有任何断言盯着它们不跑偏** ——
 * 改一处漏一处不会有东西变红,而表现是「拍照记的那一餐」和「手动记的那一餐」
 * 落在不同的餐次上。这次合成一处。
 *
 * 纯函数,不碰 DOM —— 可以在 Node 里直接调(`scripts/verify-loop.mjs` 第 1 节)。
 */

import type { MealSlot } from '../store/types'

/** 三餐。**顺序就是时间顺序** —— 「今天还缺哪一餐」只认这三个 */
export const MAIN_SLOTS: MealSlot[] = ['早餐', '午餐', '晚餐']

/** 三次加餐 —— 同样是时间顺序 */
export const SNACK_SLOTS: MealSlot[] = ['上午加餐', '下午加餐', '夜宵']

/**
 * 全部餐次,**按时间顺序**(加餐插在两餐之间)。
 *
 * 这个顺序是给「按餐次分组」用的 —— `derive.dayStats` 的分桶、首页那行
 * 每餐 kcal、发给食衡的 `todayIntake.meals`:那时要的是**从早到晚**。
 *
 * ⚠️ **面板上那排按钮用的不是这个顺序**,见 `SLOT_ROWS`。
 */
export const MEAL_SLOTS: MealSlot[] = ['早餐', '上午加餐', '午餐', '下午加餐', '晚餐', '夜宵']

/**
 * 面板上那排按钮的**两行**:上排三餐、下排三次加餐。
 *
 * 为什么不复用 `MEAL_SLOTS` 的顺序:六个按钮在一行里放不下 ——
 * `SegmentedControl` 的 `sm` 尺寸下每个按钮至少 46px,六个要 300px 以上,
 * 而窄屏去掉左右各 16px 的内边距只剩约 337px,还要装下「上午加餐」四个字。
 * 排成两行之后每个都写得下全名(这也是用户选的那一项)。
 *
 * 而**分行的依据是「正餐 / 加餐」而不是时间顺序**:按时间顺序排成三行两列
 * (早、上午加餐 / 午餐、下午加餐 / 晚餐、夜宵)读起来像一张时刻表,
 * 而「上面三餐、下面加餐」一眼就能看出这六个是什么关系。
 *
 * ⚠️ 两行**摊平之后**的顺序 ≠ `MEAL_SLOTS`。要按时间走的地方用 `MEAL_SLOTS`,
 * 要铺按钮的地方用 `SLOT_ROWS.flat()` —— 混用不会报错,只会让某个列表的顺序
 * 悄悄变得没道理。
 */
export const SLOT_ROWS: MealSlot[][] = [[...MAIN_SLOTS], [...SNACK_SLOTS]]

/** 这一餐是不是正餐 —— 判据只有一处,别在调用点写 `s.slot !== '夜宵'` 那种 */
export function isMainSlot(slot: string): boolean {
  return (MAIN_SLOTS as readonly string[]).includes(slot)
}

/** 这一餐是不是加餐(三档都算) */
export function isSnackSlot(slot: string): boolean {
  return (SNACK_SLOTS as readonly string[]).includes(slot)
}

/**
 * 一个钟点属于哪一餐。
 *
 * 边界一律**左闭右开**:6:00 是早餐,9:00 就是上午加餐了。
 * 五段窄窗口 [6,9) / [9,11) / [11,14) / [14,17) / [17,21),其余是夜宵。
 *
 * 夜宵那段有 9 小时 —— 比任何一个正餐窗口都长,这是**对的**:那段时间大部分
 * 在睡觉,中间没有别的餐次可归。21:00 吃的那顿和凌晨两点吃的那顿都叫夜宵。
 *
 * 只吃整数小时(不分钟):`09:30` 是上午加餐,`9` 就够判;分钟在这里没有
 * 任何一条规则会用到,引入它只会让人以为某个边界是按分钟切的。
 */
export function slotAtHour(hour: number): MealSlot {
  if (hour >= 6 && hour < 9) return '早餐'
  if (hour >= 9 && hour < 11) return '上午加餐'
  if (hour >= 11 && hour < 14) return '午餐'
  if (hour >= 14 && hour < 17) return '下午加餐'
  if (hour >= 17 && hour < 21) return '晚餐'
  return '夜宵'
}

/**
 * 现在该记哪一餐 —— 面板打开时的默认选中项。
 *
 * 默认值**只看钟点**,不看「今天已经记了哪几餐」(用户选的):一餐可以记两次
 * (加了碗饭再补记一条),而按「缺哪餐」去猜会把第二次记的午餐默认成晚餐 ——
 * 那是个用户没做过的判断。
 */
export function currentSlot(now: Date = new Date()): MealSlot {
  return slotAtHour(now.getHours())
}

/**
 * 一条**存下来的时间**属于哪一餐 —— 只给 v7→v8 的迁移用(见 `persist.ts`)。
 *
 * `time` 是 `MealEntry.time`,格式 `HH:mm`(由 `lib/date.formatTime` 产出)。
 * 解析不出来时返回 `null`,**不猜** —— 猜一个等于替用户改他的记录;
 * 而真走到这个分支说明 `MealEntry.time` 被写坏了,那是另一件事,不该由
 * 一次版本迁移顺手糊过去。
 */
export function slotForClock(time: string): MealSlot | null {
  const m = /^(\d{1,2}):(\d{2})$/.exec(time.trim())
  if (!m) return null
  const h = Number(m[1])
  if (!Number.isInteger(h) || h < 0 || h > 23) return null
  return slotAtHour(h)
}
