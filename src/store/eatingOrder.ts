/**
 * 进食顺序 —— 结果页那张「先吃什么、后吃什么」的卡的规则。
 *
 * 排出来的五档
 * ============================================================
 *   0 餐前     汤、水果
 *   1 先吃     蔬菜
 *   2 再吃     蛋奶豆 / 肉类 / 水产(都是蛋白质)
 *   3 最后吃   主食
 *   4 随餐     饮品、零食(其他) —— 没有先后可言,但**不许从卡上消失**
 *
 * 依据(中间三档)
 * ============================================================
 * 《成人糖尿病食养指南》2.3:「调整进餐顺序对控制血糖有利,养成先吃菜,
 * 最后吃主食的习惯。」
 * 《成人肥胖食养指南》2.3:「适当改变进餐顺序也是一种简单、易行、有效的减重
 * 方法。按照蔬菜-肉类-主食的顺序进餐,也有助于减少高能量食物的进食量。」
 *
 * ⚠️ 这两句里**没有汤、没有水果、没有饮料、没有零食**。下面餐前那一条是另外
 * 查的,别把两件事混成一句引用 —— 卡片脚注因此只把「菜和肉在主食前面」归给
 * 这两份指南。
 *
 * 依据(餐前那一档:汤、水果)—— **知识库里没有,是联网查的**
 * ============================================================
 *   · 上海市卫健委《吃饭换个顺序,控糖还减肥》:「可以在正餐前先摄入少量低升糖
 *     指数食物垫肚子,如水果、清淡的汤,放在正式进餐前。」
 *   · 四川省卫健委(引北京医院郭立新):「第一口应该先喝汤。」
 *   · 央广网等:通行口径是「汤→菜→肉→主食」。
 *
 * 这一档**只有卫健系统的科普/媒体口径,没有指南原文**。分量不一样:上面那两句
 * 是「食养指南」的正文,这一条是科普。代码里可以并排站,脚注里不能混成一句,
 * 所以脚注只给「菜和肉在主食前面」署那份指南的名。
 *
 * ⚠️ 查的时候踩到过一个坑,写在这儿免得下一个人再踩:糖尿病指南后面那几十份
 * **食谱**,汤几乎都写在菜单的**最后一行**(如「杂粮饭、尖椒炒肉、老黄瓜羊肉
 * 汤」)。那**是菜单的写法,不是吃法** —— 那些菜单连主食都写在第一行,而进食
 * 顺序的规矩恰恰是主食最后。**不能拿它当「汤最后喝」的依据。**
 *
 * 为什么第二档叫「蛋白质」而不是「肉类」
 * ============================================================
 * 肥胖指南的原话是「蔬菜-肉类-主食」,但库里这一档装的是蛋奶豆、肉类、水产
 * 三类,统称「肉类」会把豆腐和鲈鱼说成肉。说明词用那一档**实际装的东西**的名字。
 * (指南那句话本身仍然照引在上面,不改一个字。)
 *
 * 为什么不放进 `advice.ts`
 * ============================================================
 * `advice.ts` 的文件头把自己的职责写死了:那里面是「从这一餐的**营养值**推出来的
 * 健康建议」。这张卡是按**分类**排的,一分营养值都不看 —— 放进去会让那个文件头
 * 变成一句假话。
 *
 * 还有一条更要紧的:`advice.ts` 的 `dishIcon()` 是个带 `default: 'plate'` 的
 * `switch`,它对没想过的分类**静默**给一个盘子图标;而下面这张表对没想过的分类
 * 必须是编译错误。两件事住在同一个文件里,早晚有人来「统一」它们 —— 而那个统一
 * 一定是错的。
 *
 * ⚠️ 代价说清楚:`dishIcon()` 和下面的 `CATEGORY_ROLE` 都要按 `FoodCategory`
 * 分类,**同一件事问了两处**。它们的产物不同(一个图标、一个档位),但将来加分类
 * 时两个地方都要改。这次没有合并成一个 `categoryOf()`:那会连带改到 `advice.ts`
 * 里那条 `yes/no/unknown` 的蔬菜判断,而那条判断今天**一条断言都没有** —— 动它
 * 而不补测试是净亏。
 */

import { FOOD_BY_ID, type FoodCategory } from '../data/foods'
import type { MealItem } from './types'

/**
 * 一档的角色。
 *
 * `group` 只有五个取值,而且**就是顺序本身** —— 和 `lib/slots.ts` 里
 * 「数组顺序就是顺序」是同一条写法,不另立一套权重表。
 */
interface Role {
  /** 0 餐前 / 1 先吃 / 2 再吃 / 3 最后吃 / 4 随餐 */
  group: 0 | 1 | 2 | 3 | 4
  /** 说明词里的角色名,如「蔬菜」「蛋白质」「主食」 */
  noun: string
  /** 说明词里的动词 —— 汤是「喝」,其余是「吃」 */
  verb: '吃' | '喝'
}

/*
  ⚠️ `noun` / `verb` 在第四档(随餐)今天**用不上**:那一档的说明词就是「随餐」
  两个字,不说角色也不说动词。两个字段留着只是为了让整张表形状一致(一个分类
  一个 `Role`),不为别的。
*/

/** 肉、蛋、奶、豆、水产 —— 三类同属中间那一档,共用一份 */
const PROTEIN: Role = { group: 2, noun: '蛋白质', verb: '吃' }

/**
 * 分类 → 档位。
 *
 * 写成 `Record<FoodCategory, Role>` 而不是 `switch`,也不写成
 * `Partial<Record<…>>`:**九种分类漏了一种必须是编译错误**,而不是运行时静默
 * 少一道菜。(上一轮 `SLOT_ICON: Record<MealSlot, string>` 同一个理由。)
 *
 * ⚠️ **九类今天全都有档位,一个 `null` 都没有** —— 这是刻意的,别改回去。
 * 上一版把汤、水果、饮品、零食四类写成 `null`(「想过之后决定不排」),结果一盘
 * 有汤的饭菜里,**汤从这张卡上直接消失了**。用户的原话是「进食顺序建议中任何
 * 一个菜都不要遗漏」—— 「没有依据」和「不显示」是两回事,当初把它们当成了一回事。
 *
 * 现在没有先后依据的那几类排在**最后**、说明词写「随餐」:人还在卡上,只是不替
 * 它编一个位置。
 */
export const CATEGORY_ROLE: Record<FoodCategory, Role> = {
  汤羹: { group: 0, noun: '汤', verb: '喝' },
  水果: { group: 0, noun: '水果', verb: '吃' },
  蔬菜: { group: 1, noun: '蔬菜', verb: '吃' },
  蛋奶豆: PROTEIN,
  肉类: PROTEIN,
  水产: PROTEIN,
  主食: { group: 3, noun: '主食', verb: '吃' },
  饮品: { group: 4, noun: '饮品', verb: '喝' },
  其他: { group: 4, noun: '零食', verb: '吃' },
}

/**
 * ⚠️ **导出是为了测**:`scripts/verify-loop.mjs` 里有两条断言要读它 ——
 * 一条断「`Record` 覆盖了 `CATEGORY_ORDER` 里的每一种分类」,另一条拿一张
 * **手写的规格表**当期望值断每一类的档位。仓库里既有的做法一样
 * (`persist.ts` 的 `migrateLegacySlots` / `stripThumbs` 也是为了在 Node 里测
 * 才导出的)。
 *
 * 那两条断言**红得起来**,不是摆设:`scripts/` 那一堆不参与 `typecheck`
 * (`tsconfig.json` 只包含 `src`、`api`、`vite.config.ts`),脚本走 `ssrLoadModule`,
 * esbuild 只剥类型不做检查 —— 所以「有人删掉这张表里的一行」在 `npm run typecheck`
 * 会红,而在 `npm run verify` 下跑得动,红的就是那条覆盖断言。
 */

export interface OrderStep {
  /** 这一步吃的那道菜 —— **就是菜品卡上那个名字**,不是食物库里的名字 */
  name: string
  /** 说明词:「餐前喝汤」「先吃蔬菜」「再吃蛋白质」「最后吃主食」「随餐」 */
  note: string
}

/** 五个档位。数组顺序就是先后 —— 下面的分档直接照它铺 */
const GROUPS = [0, 1, 2, 3, 4] as const

/**
 * 说明词。
 *
 * ⚠️ 「先吃蔬菜」和「最后吃主食」是**照指南原文写的**,不是按位置算出来的 ——
 * 《糖尿病食养指南》那句原话就是「养成先吃菜,最后吃主食的习惯」。所以蔬菜恒
 * 「先吃」、主食恒「最后吃」,只有中间那个「蛋白质」是变的:**没有蔬菜那一档时**
 * (一盘排骨 + 米饭)它就是第一个进嘴的,再说「再吃」就凭空多出一个「先」。
 *
 * 上一版是按位置算的(第一个「先吃」、最后一个「最后吃」),那会在一盘
 * 只有汤和青菜的餐盘上把青菜说成「最后吃蔬菜」—— 按位置算和照指南原文写,
 * 后者才对。
 */
function noteFor(role: Role, hasVeg: boolean): string {
  switch (role.group) {
    case 0:
      return `餐前${role.verb}${role.noun}`
    case 1:
      return `先吃${role.noun}`
    case 2:
      return `${hasVeg ? '再吃' : '先吃'}${role.noun}`
    case 3:
      return `最后吃${role.noun}`
    case 4:
      return '随餐'
  }
}

/**
 * 从这一盘的菜品里排出进食顺序。不足两档时返回**空数组**(整张卡不渲染)。
 *
 * 纯逻辑,不碰 DOM —— 可在 Node 里直接测。
 */
export function deriveEatingOrder(items: MealItem[]): OrderStep[] {
  /*
    分档。`GROUPS` 的顺序决定档与档的先后,`items` 的顺序决定**档内**的先后 ——
    也就是上面那张菜品卡里从上到下的顺序,这里不改写它(不按克数排、不按名字排)。

    查分类走 `FOOD_BY_ID` —— `data/foods.ts` 的文档明文许可这个用法
    (「给食物库自己的条目查分类」)。这里要的**不是**一道菜的营养,那个入口
    只有 `lib/nutrition.ts` 的 `per100gOf`,别混。
  */
  const tiers = GROUPS.map((g) => ({
    group: g,
    rows: items.flatMap((it) => {
      const category = FOOD_BY_ID.get(it.foodId)?.category
      if (category === undefined) return []
      const role = CATEGORY_ROLE[category]
      /*
        `!role` 挡的是**表里漏了一行**。类型上 `Record` 已经保证了不漏,但
        `scripts/` 不参与 `typecheck`,漏一行在 `npm run verify` 下是跑得动的 ——
        这里只是不让它炸成一个看不懂的 TypeError,真正会红的是 `verify-loop`
        那条「覆盖九种分类」,它会指名道姓说少的是哪一类。
      */
      if (!role || role.group !== g) return []
      return [{ name: it.name, role }]
    }),
  })).filter((t) => t.rows.length > 0)

  /*
    不足两档就不给这张卡 —— 一道菜没有「顺序」可言。

    判据是**档数 ≥ 2**,不是菜数 ≥ 2:米饭 + 排骨(两档、两道菜)**要**出现,
    那正是「先吃肉、最后吃饭」这句建议本身;而米饭 + 馒头只有一档,排出来的
    「① 米饭 ② 馒头」不是建议,是噪音。

    ⚠️ **分类查不到的菜(`web:` / `unmatched:` 的哨兵 id)在这一步之前就被丢掉了,
    但它们不撤掉整张卡。** 这一条和 `advice.ts` 那条蔬菜判断**正好相反**,别来
    「修」:
      · 那条断的是**否定**(「这一餐没有蔬菜或水果」),分类未知时这句话可能说错,
        所以整条不说;
      · 这张卡断的是**肯定**(「先吃这几道」),分类未知的菜只是不进这个列表 ——
        列表里没有它,不等于说了它什么。
    代价:一盘里有联网查到的「清炒时蔬」时,顺序里不会出现它,也就是**这一道
    没有顺序说明**。屏上它照样有一行(`eatingPlan.ts` 会把库外菜补成没有档的
    那种行),只是那一行不带顺序说明 —— 用户看到的不是「这盘没菜」,而是
    「这道菜没说先后」。**接受**。
  */
  if (tiers.length < 2) return []

  /*
    「蛋白质」那一档的说明词要不要说「再吃」,取决于**有没有蔬菜那一档** ——
    所以先把「这一盘有没有蔬菜」问清楚,再逐条写说明词。
  */
  const hasVeg = tiers.some((t) => t.group === 1)

  return tiers.flatMap((t) => t.rows.map((r) => ({ name: r.name, note: noteFor(r.role, hasVeg) })))
}
